/** Stroke a rune into a 2D context. (x,y) is the top-left of a size×size box. */
export function drawRune(ctx, rune, x, y, size) {
  ctx.beginPath()
  for (const [[ax, ay], [bx, by]] of rune) {
    ctx.moveTo(x + ax * size, y + ay * size)
    ctx.lineTo(x + bx * size, y + by * size)
  }
  ctx.stroke()
}

/** Rune as an SVG path `d` string for a 24×24 box. */
export function runePath(rune, size = 24) {
  return rune
    .map(([[ax, ay], [bx, by]]) => `M${(ax * size).toFixed(1)} ${(ay * size).toFixed(1)}L${(bx * size).toFixed(1)} ${(by * size).toFixed(1)}`)
    .join(' ')
}

/** Deterministic PRNG (mulberry32). */
export function rng(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
